const CHARS = Object.keys(GLYPHS).join('');
const CELL_W = 6;
const CELL_H = 8;

export const PIXEL_FONT_KEY = 'pixel';

export function createPixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.exists(PIXEL_FONT_KEY)) return;

  const canvasTexture = scene.textures.createCanvas('pixel-font-sheet', CELL_W * CHARS.length, CELL_H);
  if (!canvasTexture) throw new Error('Could not create the pixel font texture.');
  const ctx = canvasTexture.getContext();
  ctx.fillStyle = '#ffffff';

  [...CHARS].forEach((char, index) => {
    GLYPHS[char].forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit === '1') ctx.fillRect(index * CELL_W + x, y, 1, 1);
      });
    });
  });
  canvasTexture.refresh();

  const entry = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: 'pixel-font-sheet',
    width: CELL_W,
    height: CELL_H,
    chars: CHARS,
    charsPerRow: CHARS.length,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: 0,
  });
  scene.cache.bitmapFont.add(PIXEL_FONT_KEY, entry);
}

export const PIXEL_FONT_CELL = { width: CELL_W, height: CELL_H };
